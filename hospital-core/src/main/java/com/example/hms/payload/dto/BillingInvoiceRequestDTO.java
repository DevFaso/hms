package com.example.hms.payload.dto;

import com.example.hms.enums.InvoiceStatus;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.UUID;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class BillingInvoiceRequestDTO {

    private String id;

    /**
     * The patient, as picked in the portal (QA D92): a patient with no e-mail
     * (a phone-only registration) can be invoiced. Must be registered at the
     * caller's hospital. Either this or {@link #patientEmail} is required.
     */
    private UUID patientId;

    /** Legacy key, used only when {@link #patientId} is absent. */
    private String patientEmail;

    /**
     * Ignored: the invoice is created at the caller's acting hospital and
     * never moves (a hospital named in the body is a claim, not a scope).
     */
    private String hospitalName;

    /** QA D230: optional; when sent it must be the acting hospital, or the request is refused. */
    private UUID hospitalId;

    private String encounterReference;

    /** Ignored: the server allocates the number per hospital (QA D94). */
    @Size(max = 50)
    private String invoiceNumber;

    @NotNull
    private LocalDate invoiceDate;

    @NotNull
    private LocalDate dueDate;

    /**
     * The amount of an invoice with no lines. Once the invoice has lines the
     * total is their sum and this is ignored (QA D72).
     */
    @Digits(integer = 10, fraction = 2)
    @PositiveOrZero
    private BigDecimal totalAmount;

    /**
     * Ignored: the amount paid only ever moves through a recorded payment
     * (QA D91).
     */
    private BigDecimal amountPaid;

    /**
     * DRAFT, SENT or CANCELLED. PAID and PARTIALLY_PAID follow the recorded
     * payments and are refused here unless unchanged (QA D91). Null keeps the
     * current status (DRAFT on create).
     */
    private InvoiceStatus status;

    @Size(max = 2048)
    private String notes;

    /**
     * Idempotency key generated by the client once per create form (QA D94):
     * a second create with the same key returns the first invoice.
     */
    private UUID clientRequestId;

    /**
     * QA D529: the visit or stay named by {@code encounterReference} already
     * has an invoice. A second one is refused (409) unless the clerk confirms
     * it is a deliberate supplementary invoice.
     */
    private Boolean supplementary;
}
