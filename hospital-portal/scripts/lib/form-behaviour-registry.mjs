/**
 * QA round 29 (D1245 / D1256 / D1272 / D1301 / D1341 NOT_FIXED three rounds
 * running): the portal guards read templates as text, and QA kept finding
 * the forms the text rules could not see. The behavioural spec
 * (`src/app/testing/form-behaviour.spec.ts`) mounts every component that
 * renders a form and drives it: empty submit, server `fieldErrors`.
 *
 * This module ENUMERATES those components from the code, so a new form is
 * driven without anyone listing it: every `@Component` under the covered
 * directories whose template (its `.html` or an inline `template:`) holds a
 * submit (`<form`, `type="submit"`, `appSubmitGuard`, `(ngSubmit)`) or a field
 * and a button (a dialog sent by a `(click)`).
 * `form-behaviour-registry.test.mjs` fails when the generated registry
 * (`src/app/testing/form-behaviour.registry.ts`) is not the current list;
 * `node scripts/lib/form-behaviour-registry.mjs --write` rewrites it.
 *
 * Covered directories: the front-office screens (fix/r29-portal-front-office).
 * Another branch adds its directories to `COVERED_DIRS`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { walk } from './walk.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PORTAL_DIR = resolve(HERE, '..', '..');
const APP_DIR = join(PORTAL_DIR, 'src', 'app');
export const REGISTRY_FILE = join(APP_DIR, 'testing', 'form-behaviour.registry.ts');

/** The directories (under src/app) whose forms the behavioural spec drives. */
export const COVERED_DIRS = [
  'appointments',
  'billing',
  'checkout',
  'patient-portal',
  'patients',
  'pharmacy',
  'reception',
];

const SUBMIT_RE = /<form[\s>]|type="submit"|appSubmitGuard|\(ngSubmit\)/;
/** A field and a button: a dialog or panel sent by a `(click)` (the payment dialogs). */
const FIELD_RE = /<(?:input|select|textarea)[\s>]/;
const BUTTON_RE = /<button[\s>]/;

function rendersForm(template) {
  return SUBMIT_RE.test(template) || (FIELD_RE.test(template) && BUTTON_RE.test(template));
}

/** The template text of a component source: its templateUrl file, or its inline template. */
function templateOf(file, text) {
  const url = /templateUrl:\s*['"`]([^'"`]+)['"`]/.exec(text);
  if (url) {
    const html = resolve(dirname(file), url[1]);
    return existsSync(html) ? readFileSync(html, 'utf8') : '';
  }
  const inline = /template:\s*`([\s\S]*?)`\s*,?\s*(?:styles|styleUrl|host|changeDetection|\})/.exec(
    text,
  );
  return inline ? inline[1] : '';
}

/**
 * Every covered component with a submit in its template, sorted by file:
 * `{ name, file }` (file relative to src/app, without `.ts`).
 */
export function formComponents() {
  const out = [];
  for (const dir of COVERED_DIRS) {
    const abs = join(APP_DIR, dir);
    if (!existsSync(abs)) continue;
    for (const file of walk(abs, ['.ts'])) {
      if (file.endsWith('.spec.ts')) continue;
      const text = readFileSync(file, 'utf8');
      const decorated = /@Component\s*\(\s*\{[\s\S]*?\}\s*\)\s*export\s+class\s+(\w+)/.exec(text);
      if (!decorated) continue;
      if (!rendersForm(templateOf(file, text))) continue;
      out.push({
        name: decorated[1],
        file: relative(APP_DIR, file).replaceAll('\\', '/').replace(/\.ts$/, ''),
      });
    }
  }
  return out.sort((a, b) => a.file.localeCompare(b.file));
}

/** The registry source for `components`. */
export function registrySource(components = formComponents()) {
  const lines = [
    '// GENERATED by scripts/lib/form-behaviour-registry.mjs (--write). Do not edit by hand:',
    '// scripts/lib/form-behaviour-registry.test.mjs fails when this is not the current list.',
    "import { Type } from '@angular/core';",
    '',
  ];
  for (const c of components) lines.push(`import { ${c.name} } from '../${c.file}';`);
  lines.push(
    '',
    '/** Every covered component whose template holds a submit (form-behaviour.spec.ts). */',
    'export const FORM_BEHAVIOUR_COMPONENTS: readonly { name: string; file: string; type: Type<unknown> }[] = [',
  );
  for (const c of components) {
    lines.push(`  { name: '${c.name}', file: '${c.file}', type: ${c.name} },`);
  }
  lines.push('];', '');
  return lines.join('\n');
}

if (process.argv.includes('--write')) {
  writeFileSync(REGISTRY_FILE, registrySource());
  console.log(`wrote ${relative(PORTAL_DIR, REGISTRY_FILE)}`);
}
